#!/usr/bin/env python3
# Generates an ESP32 partitions.csv from ESP32_* environment variables and
# emits the resolved offsets/sizes as bash-sourceable key=value lines for
# the calling shell to consume.
#
# Invoked from targetenv_esp32.sh only when ESP32_FLASH_SIZE is set in the
# active config.mk; otherwise the legacy middleware-supplied partition table
# is used unchanged.
#
# Required env vars:
#   ESP32_FLASH_SIZE         Flash size string accepted by esptool (e.g. "8MB")
#   ESP32_PART_FACTORY_SIZE  Size of factory app partition (e.g. "1.8M", "0x1cc000")
#   ESP32_PART_STORAGE_SIZE  Size of LittleFS "storage" data partition
#
# Optional env vars (with defaults):
#   ESP32_PART_NVS_SIZE          0x4000
#   ESP32_PART_PHY_INIT_SIZE     0x1000
#   ESP32_PART_OTA_ENABLED       no
#   ESP32_PART_OTA_SIZE          (required if OTA enabled, e.g. 1.8M)
#   ESP32_PART_APPDATA_SIZE      0x80000   (set empty to omit the partition)
#   ESP32_PARTITION_TABLE_OFFSET 0x9000    (must match bootloader's compiled-in value)
#
# Usage: esp32_gen_partitions.py <csv_out> <env_out>

import os
import re
import sys

PARTITION_TABLE_BYTES = 0x1000
APP_ALIGN = 0x10000
DATA_ALIGN = 0x1000


def parse_size(s):
    s = s.strip()
    if not s:
        raise ValueError("empty size")
    if s.lower().startswith("0x"):
        return int(s, 16)
    m = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)\s*([KMG]?)B?", s, re.IGNORECASE)
    if not m:
        return int(s, 0)
    val = float(m.group(1))
    suf = m.group(2).upper()
    mult = {"": 1, "K": 1024, "M": 1024 * 1024, "G": 1024 * 1024 * 1024}[suf]
    return int(val * mult)


def fmt_hex(n):
    return f"0x{n:x}"


def require(name):
    v = os.environ.get(name, "").strip()
    if not v:
        sys.exit(f"esp32_gen_partitions: required env var {name} not set")
    return v


def optional(name, default):
    v = os.environ.get(name, "").strip()
    return v if v else default


def is_yes(s):
    return s.strip().lower() in ("yes", "y", "true", "1", "on")


def align_up(n, align):
    return (n + align - 1) & ~(align - 1)


def main(argv):
    if len(argv) != 3:
        sys.exit(f"usage: {argv[0]} <csv_out> <env_out>")
    csv_out, env_out = argv[1], argv[2]

    flash_size = parse_size(require("ESP32_FLASH_SIZE"))
    pt_offset = parse_size(optional("ESP32_PARTITION_TABLE_OFFSET", "0x9000"))
    nvs_size = parse_size(optional("ESP32_PART_NVS_SIZE", "0x4000"))
    phy_size = parse_size(optional("ESP32_PART_PHY_INIT_SIZE", "0x1000"))
    factory_size = parse_size(require("ESP32_PART_FACTORY_SIZE"))
    storage_size = parse_size(require("ESP32_PART_STORAGE_SIZE"))
    ota_enabled = is_yes(optional("ESP32_PART_OTA_ENABLED", "no"))
    ota_size = parse_size(require("ESP32_PART_OTA_SIZE")) if ota_enabled else 0
    appdata_raw = optional("ESP32_PART_APPDATA_SIZE", "0x80000")
    appdata_size = parse_size(appdata_raw) if appdata_raw else 0

    parts = []
    parts.append(("nvs", "data", "nvs", nvs_size))
    if ota_enabled:
        parts.append(("otadata", "data", "ota", 0x2000))
    parts.append(("phy_init", "data", "phy", phy_size))
    parts.append(("factory", "app", "factory", factory_size))
    if ota_enabled:
        parts.append(("ota_0", "app", "ota_0", ota_size))
        parts.append(("ota_1", "app", "ota_1", ota_size))
    parts.append(("storage", "data", "spiffs", storage_size))
    if appdata_size:
        parts.append(("appdata", "data", "spiffs", appdata_size))

    resolved = []
    cursor = pt_offset + PARTITION_TABLE_BYTES
    for name, ptype, subtype, size in parts:
        align = APP_ALIGN if ptype == "app" else DATA_ALIGN
        offset = align_up(cursor, align)
        if offset + size > flash_size:
            sys.exit(
                f"esp32_gen_partitions: partition '{name}' "
                f"({fmt_hex(offset)}+{fmt_hex(size)}) overflows flash "
                f"({fmt_hex(flash_size)}). Reduce ESP32_PART_* sizes "
                f"or increase ESP32_FLASH_SIZE."
            )
        resolved.append((name, ptype, subtype, offset, size))
        cursor = offset + size

    with open(csv_out, "w") as f:
        f.write("# Generated by esp32_gen_partitions.py from ESP32_* env vars.\n")
        f.write("# Edit ESP32_PART_* in target/platform/<TARGET>/config.mk, not here.\n")
        f.write("# Name,     Type,   SubType,    Offset,     Size,       Flags\n")
        for name, ptype, subtype, offset, size in resolved:
            f.write(
                f"{name:<10}, {ptype:<5}, {subtype:<8}, "
                f"{fmt_hex(offset):<10}, {fmt_hex(size):<10},\n"
            )

    name_to = {n: (o, s) for n, _, _, o, s in resolved}
    with open(env_out, "w") as f:
        f.write(f"ESP32_GEN_FLASH_SIZE_BYTES={flash_size}\n")
        f.write(f"ESP32_GEN_FLASH_SIZE_HEX={fmt_hex(flash_size)}\n")
        f.write(f"ESP32_GEN_PARTITION_TABLE_OFFSET={fmt_hex(pt_offset)}\n")
        f.write(f"ESP32_GEN_FACTORY_OFFSET={fmt_hex(name_to['factory'][0])}\n")
        f.write(f"ESP32_GEN_FACTORY_SIZE={fmt_hex(name_to['factory'][1])}\n")
        f.write(f"ESP32_GEN_STORAGE_OFFSET={fmt_hex(name_to['storage'][0])}\n")
        f.write(f"ESP32_GEN_STORAGE_SIZE={fmt_hex(name_to['storage'][1])}\n")
        if "appdata" in name_to:
            f.write(f"ESP32_GEN_HAS_APPDATA=yes\n")
            f.write(f"ESP32_GEN_APPDATA_OFFSET={fmt_hex(name_to['appdata'][0])}\n")
            f.write(f"ESP32_GEN_APPDATA_SIZE={fmt_hex(name_to['appdata'][1])}\n")
        else:
            f.write(f"ESP32_GEN_HAS_APPDATA=no\n")
        if ota_enabled:
            f.write(f"ESP32_GEN_OTA_ENABLED=yes\n")
            f.write(f"ESP32_GEN_OTA0_OFFSET={fmt_hex(name_to['ota_0'][0])}\n")
            f.write(f"ESP32_GEN_OTA1_OFFSET={fmt_hex(name_to['ota_1'][0])}\n")
        else:
            f.write(f"ESP32_GEN_OTA_ENABLED=no\n")

    print(f"esp32_gen_partitions: wrote {csv_out}", file=sys.stderr)
    print(f"esp32_gen_partitions: wrote {env_out}", file=sys.stderr)
    for name, ptype, subtype, offset, size in resolved:
        print(
            f"  {name:<10} {ptype:<5} {subtype:<8} "
            f"@ {fmt_hex(offset):<10} size {fmt_hex(size)}",
            file=sys.stderr,
        )


if __name__ == "__main__":
    main(sys.argv)
