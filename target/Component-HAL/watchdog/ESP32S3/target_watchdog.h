/*
 * target_watchdog.h
 * Inline functions are used for watchdog timer related stuff because we do not want function calling overhead
 */

#ifndef _TARGET_WATCHDOG_H_
#define _TARGET_WATCHDOG_H_

#include "ehs_fb_types.h"
#include "hal_watchdog2.h"
#include <stdint.h>

#define TCTWDT_ESP32S3_TIMG0_BASE 0x6001F000
#define TCTWDT_ESP32S3_TIMG1_BASE 0x60020000
#define TCTWDT_ESP32S3_TIMG_WDT_CONFIG0_OFFSET 0x0048
#define TCTWDT_ESP32S3_TIMG_WDT_CONFIG1_OFFSET 0x004C
#define TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDTCONFIG2_REG_OFFSET 0x0050
#define TCTWDT_ESP32S3_TIMG_WDT_FEED_OFFSET 0x0060
#define TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET 0x0064
#define TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE 0x50d83aa1
#define TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDT_EN_VALUE ((uint32_t)(1 << 31))

#define TCTWDT_ESP32S3_LPMGMT_BASE 0x60008000
#define TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_CONF_REG_OFFSET 0x00B4
#define TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET 0x00B8
#define TCTWDT_ESP32S3_RTC_CNTL_RTC_CNTL_RTC_STORE1_REG_OFFSET 0x0054
#define TCTWDT_ESP32S3_RTC_CNTL_RTC_CNTL_RTC_WDTCONFIG1_REG_OFFSET 0x009C
#define TCTWDT_ESP32S3_RTC_CNTL_SWD_FEED_VALUE ((uint32_t)(1 << 29))
#define TCTWDT_ESP32S3_RTC_CNTL_SWD_DISABLE_VALUE ((uint32_t)(1 << 30))
#define TCTWDT_ESP32S3_RTC_CNTL_SWD_AUTO_FEED_EN_VALUE ((uint32_t)(1 << 31))
#define TCTWDT_ESP32S3_RTC_CNTL_WDT_WRITEPROTECT_MAGIC_VALUE 0x8f1d312a

#define TCTWDT_ESP32S3_EFUSE_BASE 0x60007000
#define TCTWDT_ESP32S3_EFUSE_RD_REPEAT_DATA1_REG_OFFSET 0x0034
#define TCTWDT_ESP32S3_EFUSE_EFUSE_WDT_DELAY_SEL_VALUE_OFFSET 16

#define EHS_REG32(x) (*((volatile uint32_t *) x))

#define TCTWDT_ESP32S3_EFUSE_EFUSE_WDT_DELAY_SEL_VALUE ((EHS_REG32(TCTWDT_ESP32S3_EFUSE_BASE + TCTWDT_ESP32S3_EFUSE_RD_REPEAT_DATA1_REG_OFFSET) >> TCTWDT_ESP32S3_EFUSE_EFUSE_WDT_DELAY_SEL_VALUE_OFFSET) & (0b11))

// This is the calibrated slow clock period in microseconds
#define TCTWDT_ESP32S3_RTC_RTC_CNTL_RTC_STORE1_REG_VALUE ((uint32_t)(EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_CNTL_RTC_STORE1_REG_OFFSET)))

#define TCTWDT_ESP32S3_TIMG_WDTCONFIG1_TIMG_WDT_CLK_PRESCALE_VALUE (((uint32_t)EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_CONFIG1_OFFSET)) >> 16)

#define TCTWDT_ESP32S3_TIMG_MWDT_PERIOD_MULTIPLIER (80u)

static inline void EhsTWatchdogEnable() {
    // Enable Super watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = TCTWDT_ESP32S3_RTC_CNTL_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_CONF_REG_OFFSET) &= ~TCTWDT_ESP32S3_RTC_CNTL_SWD_DISABLE_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = 0;

    // Enable TIMG0 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_CONFIG0_OFFSET) |= TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDT_EN_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
    
    // Enable TIMG1 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_CONFIG0_OFFSET) |= TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDT_EN_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
}

static inline void EhsTWatchdogDisable() {
    // Disable Super watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = TCTWDT_ESP32S3_RTC_CNTL_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_CONF_REG_OFFSET) |= TCTWDT_ESP32S3_RTC_CNTL_SWD_DISABLE_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = 0;

    // Disable TIMG0 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_CONFIG0_OFFSET) &= ~TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDT_EN_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
    
    // Disable TIMG1 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_CONFIG0_OFFSET) &= ~TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDT_EN_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
}

static inline void EhsTWatchdogKick() {
    // Feed Super watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = TCTWDT_ESP32S3_RTC_CNTL_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_CONF_REG_OFFSET) |= TCTWDT_ESP32S3_RTC_CNTL_SWD_FEED_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = 0;

    // Feed TIMG0 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_FEED_OFFSET) = 1;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;

    // Feed TIMG1 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_FEED_OFFSET) = 1;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
}

static inline void EhsTWatchdogModify( ehs_uint32 period_us ) {
    // Feed Super watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = TCTWDT_ESP32S3_RTC_CNTL_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_CNTL_RTC_WDTCONFIG1_REG_OFFSET) = (((uint32_t)period_us) / TCTWDT_ESP32S3_RTC_RTC_CNTL_RTC_STORE1_REG_VALUE) >> (TCTWDT_ESP32S3_EFUSE_EFUSE_WDT_DELAY_SEL_VALUE + 1);
    EHS_REG32(TCTWDT_ESP32S3_LPMGMT_BASE + TCTWDT_ESP32S3_RTC_CNTL_RTC_SWD_WPROTECT_REG_OFFSET) = 0;

    // Feed TIMG0 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDTCONFIG2_REG_OFFSET) = period_us * TCTWDT_ESP32S3_TIMG_MWDT_PERIOD_MULTIPLIER / TCTWDT_ESP32S3_TIMG_WDTCONFIG1_TIMG_WDT_CLK_PRESCALE_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG0_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;

    // Feed TIMG1 watchdog timer
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_MAGIC_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_TIMG_WDTCONFIG2_REG_OFFSET) = period_us * TCTWDT_ESP32S3_TIMG_MWDT_PERIOD_MULTIPLIER / TCTWDT_ESP32S3_TIMG_WDTCONFIG1_TIMG_WDT_CLK_PRESCALE_VALUE;
    EHS_REG32(TCTWDT_ESP32S3_TIMG1_BASE + TCTWDT_ESP32S3_TIMG_WDT_WRITEPROTECT_OFFSET) = 0;
}

#endif//_TARGET_WATCHDOG_H_
